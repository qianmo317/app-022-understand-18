const out = {};
let missing = 0;
for (const ch of chars) {
  const file = resolve(pkgDir, `${ch}.json`);
  if (!existsSync(file)) { missing++; continue; }
  const data = JSON.parse(readFileSync(file, 'utf-8'));
  if (!Array.isArray(data.strokes) || data.strokes.length === 0) { missing++; continue; }
  // 只保留必要字段，减小体积
  out[ch] = { strokes: data.strokes, medians: data.medians };
}

